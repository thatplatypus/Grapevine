def parts(x):
    if x == 0.0:
        return (0, 0)
    m, e = math.frexp(x)
    M = int(m * (1 << 53))
    E = e - 53
    while M % 2 == 0 and M != 0:
        M //= 2
        E += 1
    return (M, E)

def shortest(x):
    for n in (15, 16, 17):
        s = '%.*e' % (n - 1, x)
        if float(s) == x:
            return s
    return '%.16e' % x

def written(x):
    if x != x or x in (float('inf'), float('-inf')):
        return 'null'
    if x == 0:
        return '0.0'
    sign = '-' if x < 0 else ''
    s = shortest(abs(x))
    mant, exp = s.split('e')
    digits = mant.replace('.', '').rstrip('0') or '0'
    e10 = int(exp)
    if -5 <= e10 < 15:
        if e10 >= 0:
            whole = digits[:e10 + 1].ljust(e10 + 1, '0')
            frac = digits[e10 + 1:] or '0'
            return sign + whole + '.' + frac
        return sign + '0.' + '0' * (-e10 - 1) + digits
    return sign + digits[0] + '.' + (digits[1:] or '0') + 'e' + str(e10)

